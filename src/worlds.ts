export const TOTAL_SECONDS = 16

const summed = WORLDS.reduce((sum, world) => sum + world.duration, 0)
if (Math.abs(summed - TOTAL_SECONDS) > 0.001) {
  throw new Error(`Timeline is ${summed}s, expected ${TOTAL_SECONDS}s`)
}

export function startOf(index: number): number {
  let time = 0
  const last = Math.max(0, Math.min(index, WORLDS.length - 1))
  for (let i = 0; i < last; i += 1) time += WORLDS[i].duration
  return time
}

export function worldAt(time: number): { index: number; local: number; world: WorldDef } {
  const span = TOTAL_SECONDS
  let t = ((time % span) + span) % span
  if (t >= span) t = 0
  let acc = 0
  for (let i = 0; i < WORLDS.length; i += 1) {
    const world = WORLDS[i]
    if (t < acc + world.duration || i === WORLDS.length - 1) {
      return { index: i, local: Math.max(0, t - acc), world }
    }
    acc += world.duration
  }
  const last = WORLDS.length - 1
  return { index: last, local: 0, world: WORLDS[last] }
}

function smooth(u: number): number {
  const t = Math.min(1, Math.max(0, u))
  return t * t * (3 - 2 * t)
}

/** 0 except during the final room, where the cup rises, holds, and lowers. */
export function sipAmount(local: number, finale: boolean): number {
  if (!finale) return 0
  if (local < 0.22) return 0
  if (local < 0.72) return smooth((local - 0.22) / 0.5)
  if (local < 1.18) return 1
  if (local < 1.68) return 1 - smooth((local - 1.18) / 0.5)
  return 0
}

/** A small extra wrist tilt at the lip, so the sip reads. */
export function drinkPulse(local: number, finale: boolean): number {
  if (!finale || local < 0.8 || local > 1.08) return 0
  return Math.sin(((local - 0.8) / 0.28) * Math.PI)
}

if (sipAmount(0.95, true) !== 1) throw new Error('sip should hold at the lips')
if (sipAmount(1.9, true) !== 0) throw new Error('sip must settle before the loop')
if (sipAmount(0.4, false) !== 0) throw new Error('body stays locked outside the finale')
